public class AbonneDTO {

	private String codeAbonne;

	private String nomAbonne;

	private String prenomAbonne;

	private String msisdn;

	private String adresseAbonne;

	private String regionAbonne;

	private String communeAbonne;

	private String quartier;

	private String offre;

	private String message;

	public String getCodeAbonne() {
		return codeAbonne;
	}

	public void setCodeAbonne(String codeAbonne) {
		this.codeAbonne = codeAbonne;
	}

	public String getNomAbonne() {
		return nomAbonne;
	}

	public void setNomAbonne(String nomAbonne) {
		this.nomAbonne = nomAbonne;
	}

	public String getPrenomAbonne() {
		return prenomAbonne;
	}

	public void setPrenomAbonne(String prenomAbonne) {
		this.prenomAbonne = prenomAbonne;
	}

	public String getMsisdn() {
		return msisdn;
	}

	public void setMsisdn(String msisdn) {
		this.msisdn = msisdn;
	}

	public String getAdresseAbonne() {
		return adresseAbonne;
	}

	public void setAdresseAbonne(String adresseAbonne) {
		this.adresseAbonne = adresseAbonne;
	}

	public String getRegionAbonne() {
		return regionAbonne;
	}

	public void setRegionAbonne(String regionAbonne) {
		this.regionAbonne = regionAbonne;
	}

	public String getCommuneAbonne() {
		return communeAbonne;
	}

	public void setCommuneAbonne(String communeAbonne) {
		this.communeAbonne = communeAbonne;
	}

	public String getQuartier() {
		return quartier;
	}

	public void setQuartier(String quartier) {
		this.quartier = quartier;
	}

	public String getOffre() {
		return offre;
	}

	public void setOffre(String offre) {
		this.offre = offre;
	}

	public String getMessage() {
		return message;
	}

	public void setMessage(String message) {
		this.message = message;
	}

}
